-- ============================================================================
-- SQL SCHEMA: 1:1, 1:M, and M:M Relationships for PostgreSQL / Supabase
-- ============================================================================
-- This script creates:
--   1. products: Core entity (already exists or created if not)
--   2. product_details: 1:1 Relationship (Each product has 1 specification sheet)
--   3. reviews: 1:M Relationship (Each product has Many customer reviews)
--   4. categories: M:M Target entity
--   5. product_categories: M:M Junction/Pivot table (Many products <-> Many categories)
-- ============================================================================

-- Ensure uuid-ossp or pgcrypto extension is available (standard in Supabase)
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- ----------------------------------------------------------------------------
-- 1. BASE TABLE: products
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  description TEXT,
  price NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
  image_url TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- ----------------------------------------------------------------------------
-- 2. ONE-TO-ONE (1:1) RELATIONSHIP: product_details
-- ----------------------------------------------------------------------------
-- KEY CONCEPT FOR 1:1:
-- The foreign key column `product_id` has a `UNIQUE` constraint!
-- This strictly guarantees that ONE product can only have AT MOST ONE detail row.
-- If someone tries to insert a second detail row for the same product_id,
-- PostgreSQL will throw a unique violation error.
-- `ON DELETE CASCADE` ensures deleting the product cleans up its specs automatically.
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.product_details (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT NOT NULL UNIQUE REFERENCES public.products(id) ON DELETE CASCADE,
  sku TEXT NOT NULL UNIQUE,
  warranty_months INT NOT NULL DEFAULT 12,
  manufacturer TEXT,
  weight_kg NUMERIC(6, 2) DEFAULT 0.50,
  dimensions TEXT,
  origin_country TEXT DEFAULT 'United States',
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- ----------------------------------------------------------------------------
-- 3. ONE-TO-MANY (1:M) RELATIONSHIP: reviews
-- ----------------------------------------------------------------------------
-- KEY CONCEPT FOR 1:M:
-- The foreign key `product_id` references `products(id)`, but is NOT unique!
-- This allows one product to have 0, 1, or 100+ review rows.
-- Each review belongs to exactly ONE product.
-- `ON DELETE CASCADE` ensures deleting a product deletes all its reviews.
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.reviews (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
  user_name TEXT NOT NULL,
  rating SMALLINT NOT NULL CHECK (rating >= 1 AND rating <= 5),
  comment TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- Index on product_id for fast review lookups by product
CREATE INDEX IF NOT EXISTS idx_reviews_product_id ON public.reviews(product_id);

-- ----------------------------------------------------------------------------
-- 4. MANY-TO-MANY (M:M) RELATIONSHIP: categories & product_categories
-- ----------------------------------------------------------------------------
-- KEY CONCEPT FOR M:M:
-- A product can belong to MULTIPLE categories (e.g. "Electronics" AND "Audio").
-- A category can contain MULTIPLE products.
-- In relational databases, this requires a THIRD table called a
-- "Junction Table" (or Join / Pivot / Bridge Table).
-- The junction table contains foreign keys to BOTH parent tables,
-- with a composite PRIMARY KEY (product_id, category_id) to prevent duplicate links.
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  description TEXT,
  color TEXT NOT NULL DEFAULT '#2563EB',
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

CREATE TABLE IF NOT EXISTS public.product_categories (
  product_id BIGINT NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
  category_id BIGINT NOT NULL REFERENCES public.categories(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
  PRIMARY KEY (product_id, category_id)
);

-- Indexes for fast bidirectional join queries
CREATE INDEX IF NOT EXISTS idx_pc_product_id ON public.product_categories(product_id);
CREATE INDEX IF NOT EXISTS idx_pc_category_id ON public.product_categories(category_id);

-- ----------------------------------------------------------------------------
